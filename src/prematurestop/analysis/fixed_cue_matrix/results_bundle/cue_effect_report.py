"""Per-cue statistics report (`CUE_EFFECT_ANALYSIS.md`) for any results bundle.

Reads only the bundle's own `data/*.csv` and writes one Markdown file with,
for every pre-registered comparison in `data/condition_comparison_manifest.csv`:

* a per-model summary row: PCR delta at the checkpoints (macro-averaged over
  datasets) and how many datasets have a 95% paired-bootstrap CI excluding 0;
* the companion evidence-loss and answer net-harm effects;
* an appendix with every (dataset, model) cell, so no number is macro-averaged
  without its parts being visible.

It contains no interpretation: prose belongs in hand-written notes that cite
this file. Run it after `build_bundle --stage data`:

    python -m prematurestop.analysis.fixed_cue_matrix.results_bundle.cue_effect_report \\
        --bundle-root results/whitebox/e1_fixed_cue_matrix/gemma_gptoss
"""

from __future__ import annotations

import argparse
import csv
from collections import defaultdict
from pathlib import Path

from prematurestop.evaluation import config

from .docs_bundle import MODEL_SCOPE_NOTES

CHECKPOINTS = (1, 5, 10, 30)
DATASET_ORDER = ("hotpot", "2wiki", "musique", "multihoprag")
DATASET_DISPLAY = {"hotpot": "HotpotQA", "2wiki": "2WikiMultiHopQA",
                   "musique": "MuSiQue", "multihoprag": "MultiHopRAG"}


def _read(path: Path) -> list[dict]:
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def _f(x) -> float | None:
    try:
        return float(x)
    except (TypeError, ValueError):
        return None


def _sig(lo, hi) -> int:
    """+1 / -1 if the CI excludes zero on that side, else 0."""
    lo, hi = _f(lo), _f(hi)
    if lo is None or hi is None:
        return 0
    return 1 if lo > 0 else (-1 if hi < 0 else 0)


def _pp(x: float | None) -> str:
    return "n/a" if x is None else f"{x * 100:+.1f}pp"


def _mean(xs):
    xs = [x for x in xs if x is not None]
    return sum(xs) / len(xs) if xs else None


def build_report(bundle_root: Path) -> str:
    data = bundle_root / "data"
    manifest = _read(data / "condition_comparison_manifest.csv")
    deltas = _read(data / "pcr_paired_deltas_stepwise.csv")
    evidence = _read(data / "evidence_summary.csv")
    flips = _read(data / "answer_paired_flips.csv")

    models = sorted({r["model"] for r in deltas}, key=lambda m: list(config.DISPLAY_MODEL_NAMES).index(m)
                    if m in config.DISPLAY_MODEL_NAMES else 99)
    datasets = [d for d in DATASET_ORDER if any(r["dataset"] == d for r in deltas)]
    name = lambda m: config.DISPLAY_MODEL_NAMES.get(m, m)

    # (comparison, model, dataset, step) -> row
    d_idx = {(r["comparison_name"], r["model"], r["dataset"], int(r["step"])): r for r in deltas}
    e_idx = {(r["comparison_name"], r["model"], r["dataset"]): r for r in evidence}
    f_idx = {(r["condition_a"], r["condition_b"], r["model"], r["dataset"]): r for r in flips}

    out: list[str] = [
        f"# Cue Effect Analysis — {' / '.join(name(m) for m in models)}",
        "",
        "Generated by `src/prematurestop/analysis/fixed_cue_matrix/results_bundle/cue_effect_report.py` "
        "from this bundle's `data/pcr_paired_deltas_stepwise.csv`, `data/evidence_summary.csv` and "
        "`data/answer_paired_flips.csv`. Do not hand-edit: re-run the generator.",
        "",
        "## How to read this document",
        "",
        "- **Sign.** `delta = cue PCR − control PCR`. Positive means the cue made the agent "
        "complete research earlier or more often: the direction a premature-completion attack pushes.",
        "- **Significance.** `k/n sig` counts datasets whose 95% paired-bootstrap CI excludes 0 "
        "(positive side unless marked `neg`). This is per cell and not corrected for multiple "
        "comparisons; weight comes from replication across datasets and models.",
        "- **Baseline.** Each cue is compared with its pre-registered control from "
        "`data/condition_comparison_manifest.csv`. Most use `NaturalNeutral`, which isolates the cue's "
        "content from the effect of appending any text.",
        "- **Evidence loss** = control coverage − cue coverage at the final-report input (positive = "
        "the cue lost evidence). **Net harm** = (control right, cue wrong) − (control wrong, cue right), "
        "in percentage points of paired questions.",
        "- **Macro-average** = unweighted mean over datasets. The appendix shows every cell.",
        "",
    ]
    notes = [f"- `{m}`: {n}" for m in models for n in MODEL_SCOPE_NOTES.get(m, [])]
    if notes:
        out += ["## Scope notes", ""] + notes + [""]

    # ---------------------------------------------------------------- summary per comparison
    out += ["## Per-comparison summary", ""]
    peak_rows: dict[str, list[tuple[str, int, float]]] = defaultdict(list)
    for comp in manifest:
        cname, ctrl, cue = comp["comparison_name"], comp["control_condition"], comp["cue_condition"]
        out += [f"### {cname}", "",
                f"*{comp['comparison_role']}* — control `{ctrl}`, cue `{cue}`"
                + (" — **pre-registered primary**" if comp.get("is_preregistered_primary") == "True" else ""),
                "",
                "| Model | " + " | ".join(f"Δ@{k}" for k in CHECKPOINTS)
                + " | Evidence loss | Answer net harm |",
                "|---|" + "---|" * (len(CHECKPOINTS) + 2)]
        for m in models:
            cells = []
            for k in CHECKPOINTS:
                rows = [d_idx.get((cname, m, ds, k)) for ds in datasets]
                rows = [r for r in rows if r]
                mean = _mean([_f(r["delta_pcr"]) for r in rows])
                pos = sum(_sig(r["ci_lower"], r["ci_upper"]) == 1 for r in rows)
                neg = sum(_sig(r["ci_lower"], r["ci_upper"]) == -1 for r in rows)
                tag = f"{pos}/{len(rows)} sig" + (f", {neg} neg" if neg else "")
                txt = f"{_pp(mean)} ({tag})"
                cells.append(f"**{txt}**" if rows and pos == len(rows) else txt)
            ev = [e_idx.get((cname, m, ds)) for ds in datasets]
            ev = [r for r in ev if r]
            ev_mean = _mean([_f(r["paired_evidence_loss"]) for r in ev])
            ev_sig = sum(_sig(r["ci_lower"], r["ci_upper"]) != 0 for r in ev)
            fl = [f_idx.get((ctrl, cue, m, ds)) for ds in datasets]
            fl = [r for r in fl if r]
            harm = _mean([_f(r["net_harm_pct_points"]) for r in fl])
            harm_txt = "n/a" if harm is None else f"{harm:+.1f}pp"
            out.append(f"| {name(m)} | " + " | ".join(cells)
                       + f" | {_pp(ev_mean)} ({ev_sig}/{len(ev)} sig) | {harm_txt} |")
            if comp.get("control_condition") == "NaturalNeutral" and cue != "NaturalContinueSearch":
                for k in range(1, 31):
                    v = _mean([_f(d_idx[(cname, m, ds, k)]["delta_pcr"]) for ds in datasets
                               if (cname, m, ds, k) in d_idx])
                    if v is not None:
                        peak_rows[m].append((cname, k, v))
        out.append("")

    # ---------------------------------------------------------------- cross-cutting: timing and ranking
    out += ["## Cross-cutting summaries", "",
            "### Where each model's cue effect peaks",
            "",
            "For each cue measured against `NaturalNeutral` (continue-search excluded), the step at which "
            "the macro-averaged delta is largest.",
            "",
            "| Model | Comparison | Peak step | Δ at peak |", "|---|---|---|---|"]
    for m in models:
        by_comp: dict[str, tuple[int, float]] = {}
        for cname, k, v in peak_rows[m]:
            if cname not in by_comp or v > by_comp[cname][1]:
                by_comp[cname] = (k, v)
        for cname, (k, v) in sorted(by_comp.items(), key=lambda kv: -kv[1][1]):
            out.append(f"| {name(m)} | {cname} | {k} | {_pp(v)} |")
    out.append("")

    # ---------------------------------------------------------------- appendix: every cell
    out += ["## Appendix: every (dataset, model) cell", "",
            "Bold = 95% paired-bootstrap CI excludes 0. `Ctrl`/`Cue PCR@1` are the raw rates the Δ@1 "
            "column is the difference of. n = paired eligible questions at step 1.", ""]
    for comp in manifest:
        cname = comp["comparison_name"]
        out += [f"#### {cname}", "",
                f"*{comp['comparison_role']}* — control `{comp['control_condition']}`, "
                f"cue `{comp['cue_condition']}`", "",
                "| Dataset | Model | Ctrl PCR@1 | Cue PCR@1 | "
                + " | ".join(f"Δ@{k} [95% CI]" for k in CHECKPOINTS) + " | n |",
                "|---|---|---|---|" + "---|" * len(CHECKPOINTS) + "---|"]
        for ds in datasets:
            for m in models:
                r1 = d_idx.get((cname, m, ds, 1))
                if not r1:
                    out.append(f"| {DATASET_DISPLAY[ds]} | {name(m)} | — | — | "
                               + " | ".join("—" for _ in CHECKPOINTS) + " | 0 |")
                    continue
                cells = []
                for k in CHECKPOINTS:
                    r = d_idx.get((cname, m, ds, k))
                    if not r:
                        cells.append("—")
                        continue
                    v = f"{_f(r['delta_pcr']) * 100:+.1f}"
                    ci = f"[{_f(r['ci_lower']) * 100:+.1f},{_f(r['ci_upper']) * 100:+.1f}]"
                    cells.append(f"**{v}** {ci}" if _sig(r["ci_lower"], r["ci_upper"]) else f"{v} {ci}")
                out.append(f"| {DATASET_DISPLAY[ds]} | {name(m)} | {_f(r1['control_pcr']) * 100:.1f}% | "
                           f"{_f(r1['cue_pcr']) * 100:.1f}% | " + " | ".join(cells) + f" | {r1['n_paired']} |")
        out.append("")
    return "\n".join(out) + "\n"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--bundle-root", type=Path, required=True)
    args = parser.parse_args()
    text = build_report(args.bundle_root)
    (args.bundle_root / "CUE_EFFECT_ANALYSIS.md").write_text(text, encoding="utf-8")
    print(f"wrote {args.bundle_root / 'CUE_EFFECT_ANALYSIS.md'}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
